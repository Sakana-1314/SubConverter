// Build the EdgeOne Cloud Functions bundle.
//
// EdgeOne Pages runs `cloud-functions/index.js` for `/` and
// `cloud-functions/[[default]].js` for every other path. Both are thin route
// wrappers over the self-contained `_subconverter.js` bundle, so the platform
// does not need to resolve TypeScript, src/ imports, or npm dependencies.

import { build } from 'esbuild';
import { mkdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'cloud-functions');
const BUNDLE = join(OUT_DIR, '_subconverter.js');

mkdirSync(OUT_DIR, { recursive: true });

await build({
  entryPoints: [join(ROOT, 'src', 'edgeone.ts')],
  outfile: BUNDLE,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  banner: {
    js: '// Generated by `npm run build:edgeone` from src/edgeone.ts. Do not edit by hand.',
  },
  logLevel: 'warning',
});

const wrapper = `// Generated by \`npm run build:edgeone\`. Do not edit by hand.
import { handleEdgeOne } from './_subconverter.js';

export const onRequest = handleEdgeOne;
`;

writeFileSync(join(OUT_DIR, 'index.js'), wrapper);
writeFileSync(join(OUT_DIR, '[[default]].js'), wrapper);

const bytes = statSync(BUNDLE).size;
console.log(`edgeone: wrote ${OUT_DIR} (bundle ${(bytes / 1024).toFixed(1)} KiB)`);
