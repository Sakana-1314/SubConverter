/// <reference types="vite/client" />
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import baseTemplateRaw from '../../fixtures/emitter/base-template.yaml?raw';
import expectedClashRaw from '../../fixtures/emitter/expected-clash.yaml?raw';
import acl4ssrIniRaw from '../../fixtures/emitter/acl4ssr.ini?raw';
import { emitClash } from '../../../src/emitter/index';
import { isBuiltinTemplatePath } from '../../../src/emitter/default-template';
import { parseAcl4ssrIni, parseCustomProxyGroups } from '../../../src/emitter/config';
import { sanitizeTemplate } from '../../../src/emitter/template';
import type { EmitClashInput } from '../../../src/emitter/config';

function parsedTemplate(raw: string): Record<string, unknown> {
  return parse(raw, { schema: 'core', merge: false, uniqueKeys: true }) as Record<string, unknown>;
}

function goldenInput(): EmitClashInput {
  return {
    template: parsedTemplate(baseTemplateRaw),
    nodes: [
      {
        kind: 'ss',
        name: 'node1',
        server: '1.2.3.4',
        port: 8388,
        cipher: 'aes-256-gcm',
        password: 'p@ss #1',
      },
      {
        kind: 'vmess',
        name: 'node2',
        server: 'node2.example.com',
        port: 443,
        uuid: 'b831381d-6324-4d53-ad4f-8cda48b30811',
        alterId: 0,
        cipher: 'auto',
        tls: true,
        servername: 'node2.example.com',
        network: 'ws',
        ws: { path: '/ws', host: 'cdn.example.com' },
      },
    ],
    groups: [
      { name: 'PROXY', type: 'select', members: ['node1', 'node2', 'DIRECT'] },
      {
        name: 'AUTO',
        type: 'url-test',
        members: ['node1', 'node2'],
        url: 'https://www.gstatic.com/generate_204',
        interval: 300,
        tolerance: 50,
      },
    ],
    rules: [
      { type: 'DOMAIN-SUFFIX', payload: 'example.com', target: 'PROXY', params: [], raw: 'DOMAIN-SUFFIX,example.com,PROXY', line: 1, sourceId: 'inline' },
      { type: 'DOMAIN-KEYWORD', payload: 'tracker', target: 'DIRECT', params: [], raw: 'DOMAIN-KEYWORD,tracker,DIRECT', line: 2, sourceId: 'inline' },
      { type: 'MATCH', payload: '', target: 'PROXY', params: [], raw: 'MATCH,PROXY', line: 3, sourceId: 'inline' },
    ],
    providers: [],
    origin: 'https://worker.example',
    version: '1.0.0',
    options: { rulesMode: 'inline', defaultGroup: 'PROXY' },
  };
}

describe('golden Clash output', () => {
  it('matches tests/fixtures/emitter/expected-clash.yaml byte for byte', () => {
    const result = emitClash(goldenInput());
    expect(result.yaml).toBe(expectedClashRaw.replace(/\r\n/g, '\n'));
  });

  it('keeps template keys in order and drops denied/core keys', () => {
    const sanitized = sanitizeTemplate(parsedTemplate(baseTemplateRaw));
    expect(Object.keys(sanitized.template)).toEqual([
      'mixed-port',
      'allow-lan',
      'mode',
      'log-level',
      'ipv6',
      'dns',
      'tun',
      'profile',
    ]);
    expect(sanitized.warnings.map((warning) => warning.code)).toEqual([
      'W_TEMPLATE_KEY_DENIED',
      'W_TEMPLATE_CORE_IGNORED',
      'W_TEMPLATE_CORE_IGNORED',
      'W_TEMPLATE_CORE_IGNORED',
      'W_TEMPLATE_CORE_IGNORED',
      'W_TEMPLATE_KEY_DENIED',
    ]);
    expect(sanitized.template).not.toHaveProperty('script');
    expect(sanitized.template).not.toHaveProperty('unknown-option');
    expect(sanitized.template).not.toHaveProperty('proxies');
    expect(sanitized.template).not.toHaveProperty('rules');
  });

  it('reports deterministic stats and warnings', () => {
    const result = emitClash(goldenInput());
    expect(result.stats).toMatchObject({
      nodes: 2,
      groups: 2,
      rules: 3,
      providers: 0,
      warnings: 6,
    });
    expect(result.stats.warningCodes).toEqual([
      'W_TEMPLATE_CORE_IGNORED',
      'W_TEMPLATE_KEY_DENIED',
    ]);
    expect(result.warnings).toHaveLength(6);
    expect(result.yaml.startsWith('# Generated by subconverter-worker 1.0.0; nodes=2 groups=2 rules=3 warnings=6\n')).toBe(true);
    expect(result.yaml).toContain('rules:\n  - "DOMAIN-SUFFIX,example.com,PROXY"\n');
  });

  it('is deterministic across calls', () => {
    const first = emitClash(goldenInput()).yaml;
    const second = emitClash(goldenInput()).yaml;
    expect(second).toBe(first);
  });
});

describe('ACL4SSR INI fixture', () => {
  it('parses the [custom] subset without crashing on unknown keys', () => {
    const parsed = parseAcl4ssrIni(acl4ssrIniRaw);
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;

    expect(parsed.config.enableRuleGenerator).toBe(false);
    expect(parsed.config.overwriteOriginalRules).toBe(false);
    expect(parsed.config.clashRuleBase).toBe('base/all_base.tpl');
    expect(isBuiltinTemplatePath(parsed.config.clashRuleBase as string)).toBe(true);
    expect(parsed.config.rulesets).toEqual([
      'PROXY,[]DOMAIN-SUFFIX,example.com',
      'PROXY,https://example.com/rules.txt,86400',
      'DIRECT,clash-domain:https://example.com/domain.yaml',
    ]);
    expect(parsed.config.rename).toEqual(['^node(.*)@srv$1']);
    expect(parsed.config.includeRemarks).toEqual(['HK']);
    expect(parsed.config.excludeRemarks).toEqual(['(?i)expired']);
    expect(parsed.config.ignoredSections).toEqual(['common', 'template']);
    expect(parsed.config.unsupportedKeys).toEqual(['emoji', 'filter_script', 'unknown_key']);

    const codes = parsed.warnings.map((warning) => warning.code);
    expect(codes.filter((code) => code === 'W_CONFIG_SECTION_IGNORED')).toHaveLength(2);
    expect(codes.filter((code) => code === 'W_CONFIG_KEY_UNSUPPORTED')).toHaveLength(3);
  });

  it('parses custom_proxy_group lines into GroupSpecs', () => {
    const parsed = parseAcl4ssrIni(acl4ssrIniRaw);
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;

    const warnings: Parameters<typeof parseCustomProxyGroups>[1] = [];
    const specs = parseCustomProxyGroups(parsed.config.customProxyGroups, warnings);
    expect(specs.map((spec) => spec.name)).toEqual(['PROXY', 'AUTO', 'Fallback', 'LB', 'ProviderGroup']);
    expect(specs.find((spec) => spec.name === 'AUTO')).toMatchObject({
      type: 'url-test',
      url: 'https://www.gstatic.com/generate_204',
      interval: 300,
      tolerance: 50,
    });
    expect(specs.find((spec) => spec.name === 'LB')?.matchers).toEqual([
      { kind: 'node-type', pattern: 'SS' },
      { kind: 'port-range', range: '1000-2000' },
    ]);
    expect(warnings.map((warning) => warning.code)).toEqual([
      'W_GROUP_UNSUPPORTED_TYPE',
      'W_GROUP_MATCHER_INVALID',
      'W_GROUP_DIRECTIVE_UNSUPPORTED',
    ]);
  });

  it('rejects configs without [custom] and known keys', () => {
    expect(parseAcl4ssrIni('')).toEqual({
      ok: false,
      code: 'invalid_config',
      message: 'config is empty',
    });
    expect(parseAcl4ssrIni('just some text')).toMatchObject({
      ok: false,
      code: 'invalid_config',
    });
    expect(parseAcl4ssrIni(`[custom]\n# ${'x'.repeat(256 * 1024)}`)).toMatchObject({
      ok: false,
      code: 'invalid_config',
    });
  });
});
